// Generates src/data/islSignsCatalog.generated.ts from src/data/isl_signs_catalog.csv.
//
// The CSV is the source of truth for which signs exist in the catalog
// ("Category","Sign"). Re-run after editing it:
//
//   npm run signs:build
//
// This script only reads the CSV. It does not add, translate or infer
// anything: media availability is decided separately in src/data/islSigns.ts
// by checking which video files the app actually ships.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const csvPath = resolve(here, '../src/data/isl_signs_catalog.csv');
const outPath = resolve(here, '../src/data/islSignsCatalog.generated.ts');

/** Minimal RFC-4180 style parser (quoted fields, escaped quotes, CRLF, BOM). */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;
  const src = text.replace(/^﻿/, '');
  for (let i = 0; i < src.length; i++) {
    const ch = src[i];
    if (inQuotes) {
      if (ch === '"') {
        if (src[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      inQuotes = true;
    } else if (ch === ',') {
      row.push(field);
      field = '';
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && src[i + 1] === '\n') i++;
      row.push(field);
      field = '';
      if (row.some((cell) => cell.trim() !== '')) rows.push(row);
      row = [];
    } else {
      field += ch;
    }
  }
  if (field !== '' || row.length > 0) {
    row.push(field);
    if (row.some((cell) => cell.trim() !== '')) rows.push(row);
  }
  return rows;
}

function slug(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

const rows = parseCsv(readFileSync(csvPath, 'utf8'));
const [header, ...body] = rows;
const categoryIdx = header.findIndex((h) => h.trim().toLowerCase() === 'category');
const signIdx = header.findIndex((h) => h.trim().toLowerCase() === 'sign');
if (categoryIdx < 0 || signIdx < 0) {
  throw new Error('CSV must have "Category" and "Sign" columns');
}

const seen = new Set();
const entries = [];
for (const cells of body) {
  const category = (cells[categoryIdx] ?? '').trim();
  const sign = (cells[signIdx] ?? '').trim();
  if (!category || !sign) continue;
  let id = slug(sign);
  if (seen.has(id)) id = `${slug(category)}-${id}`;
  if (seen.has(id)) throw new Error(`Duplicate sign id for "${sign}" in "${category}"`);
  seen.add(id);
  entries.push({ id, category, sign });
}

const lines = entries.map(
  (e) => `  { id: ${JSON.stringify(e.id)}, category: ${JSON.stringify(e.category)}, sign: ${JSON.stringify(e.sign)} },`
);

const output = `// AUTO-GENERATED by scripts/build-signs-catalog.mjs from src/data/isl_signs_catalog.csv.
// Do not edit by hand — edit the CSV and run \`npm run signs:build\`.

export interface IslCatalogRow {
  id: string;
  category: string;
  sign: string;
}

export const ISL_CATALOG_ROWS: IslCatalogRow[] = [
${lines.join('\n')}
];
`;

writeFileSync(outPath, output);
console.log(`Wrote ${entries.length} signs to ${outPath}`);
